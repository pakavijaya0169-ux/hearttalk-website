-- HeartTalk Admin Reports Management
-- Run in Supabase SQL Editor. Admin-only access is checked inside every RPC.

create table if not exists public.hearttalk_admin_audit_log (
  id bigint generated by default as identity primary key,
  admin_user_id uuid not null references auth.users(id) on delete restrict,
  action text not null,
  target_type text not null,
  target_id text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.hearttalk_admin_audit_log enable row level security;
revoke all on public.hearttalk_admin_audit_log from anon, authenticated;

create or replace function public.admin_list_user_reports()
returns table (
  report_id bigint,
  reporter_id uuid,
  reporter_name text,
  reporter_username text,
  reported_user_id uuid,
  reported_user_name text,
  reported_username text,
  reason text,
  details text,
  status text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if not exists (
    select 1 from public.hearttalk_user_roles r
    where r.user_id = auth.uid() and r.role = 'admin'
  ) then raise exception 'Admin access required'; end if;

  return query
  select
    ur.id,
    ur.reporter_id,
    coalesce(rp.display_name, 'Unknown user'),
    rp.username,
    ur.reported_user_id,
    coalesce(tp.display_name, 'Unknown user'),
    tp.username,
    ur.reason,
    ur.details,
    ur.status,
    ur.created_at
  from public.user_reports ur
  left join public.profiles rp on rp.id = ur.reporter_id
  left join public.profiles tp on tp.id = ur.reported_user_id
  order by ur.created_at desc
  limit 500;
end;
$$;

create or replace function public.admin_set_report_status(
  target_report_id bigint,
  new_status text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_status text;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if not exists (
    select 1 from public.hearttalk_user_roles r
    where r.user_id = auth.uid() and r.role = 'admin'
  ) then raise exception 'Admin access required'; end if;
  if new_status is null or new_status not in ('open','reviewing','resolved','dismissed') then
    raise exception 'Invalid report status';
  end if;

  select status into old_status
  from public.user_reports where id = target_report_id
  for update;
  if not found then raise exception 'Report not found'; end if;

  update public.user_reports
  set status = new_status
  where id = target_report_id;

  insert into public.hearttalk_admin_audit_log
    (admin_user_id, action, target_type, target_id, details)
  values
    (auth.uid(), 'report_status_changed', 'user_report', target_report_id::text,
     jsonb_build_object('from', old_status, 'to', new_status));

  return true;
end;
$$;

create or replace function public.admin_list_recent_audit_log()
returns table (
  log_id bigint,
  admin_user_id uuid,
  action text,
  target_type text,
  target_id text,
  details jsonb,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if not exists (
    select 1 from public.hearttalk_user_roles r
    where r.user_id = auth.uid() and r.role = 'admin'
  ) then raise exception 'Admin access required'; end if;

  return query
  select l.id, l.admin_user_id, l.action, l.target_type, l.target_id, l.details, l.created_at
  from public.hearttalk_admin_audit_log l
  order by l.created_at desc
  limit 100;
end;
$$;

revoke all on function public.admin_list_user_reports() from public;
revoke all on function public.admin_set_report_status(bigint,text) from public;
revoke all on function public.admin_list_recent_audit_log() from public;
grant execute on function public.admin_list_user_reports() to authenticated;
grant execute on function public.admin_set_report_status(bigint,text) to authenticated;
grant execute on function public.admin_list_recent_audit_log() to authenticated;
