-- HeartTalk Admin Support Inbox + App Error Center
-- Additive migration. User messages stay private to the user and authorized admins.
create table if not exists public.support_threads (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references auth.users(id) on delete cascade,
 subject text not null check(char_length(subject) between 3 and 120),
 status text not null default 'open' check(status in ('open','answered','closed')),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists support_threads_user_updated_idx on public.support_threads(user_id,updated_at desc);
create index if not exists support_threads_status_updated_idx on public.support_threads(status,updated_at desc);
alter table public.support_threads enable row level security;
revoke all on public.support_threads from anon,public;
grant select,insert on public.support_threads to authenticated;
drop policy if exists "Users can view own support threads" on public.support_threads;
create policy "Users can view own support threads" on public.support_threads
 for select to authenticated using(user_id=auth.uid());
drop policy if exists "Users can create own support threads" on public.support_threads;
create policy "Users can create own support threads" on public.support_threads
 for insert to authenticated with check(user_id=auth.uid());

create table if not exists public.support_messages (
 id bigint generated by default as identity primary key,
 thread_id uuid not null references public.support_threads(id) on delete cascade,
 sender_id uuid not null references auth.users(id) on delete cascade,
 sender_role text not null check(sender_role in ('user','admin')),
 message text not null check(char_length(message) between 1 and 4000),
 created_at timestamptz not null default now()
);
create index if not exists support_messages_thread_created_idx on public.support_messages(thread_id,created_at);
alter table public.support_messages enable row level security;
drop policy if exists "Thread owners can read support messages" on public.support_messages;
create policy "Thread owners can read support messages" on public.support_messages
 for select to authenticated using(exists(select 1 from public.support_threads t where t.id=thread_id and t.user_id=auth.uid()));
drop policy if exists "Users can send support messages" on public.support_messages;
create policy "Users can send support messages" on public.support_messages
 for insert to authenticated with check(sender_id=auth.uid() and sender_role='user' and exists(select 1 from public.support_threads t where t.id=thread_id and t.user_id=auth.uid() and t.status<>'closed'));
revoke all on public.support_messages from anon,public;
grant select,insert on public.support_messages to authenticated;
grant usage,select on sequence public.support_messages_id_seq to authenticated;

create or replace function public.touch_support_thread_updated_at()
returns trigger language plpgsql security definer set search_path='' as $
begin
 update public.support_threads set updated_at=now() where id=new.thread_id;
 return new;
end; $;
drop trigger if exists support_message_touch_thread on public.support_messages;
create trigger support_message_touch_thread after insert on public.support_messages
 for each row execute function public.touch_support_thread_updated_at();

create table if not exists public.app_error_reports (
 id bigint generated by default as identity primary key,
 user_id uuid references auth.users(id) on delete set null,
 source text not null default 'web' check(source in ('web','android','ios','unknown')),
 error_type text not null default 'runtime' check(error_type in ('runtime','promise','api','manual','crash')),
 message text not null check(char_length(message) between 1 and 2000),
 stack text check(stack is null or char_length(stack)<=8000),
 page text,
 app_version text,
 status text not null default 'open' check(status in ('open','investigating','resolved','ignored')),
 created_at timestamptz not null default now(),
 resolved_at timestamptz,
 resolved_by uuid references auth.users(id)
);
create index if not exists app_error_reports_status_created_idx on public.app_error_reports(status,created_at desc);
alter table public.app_error_reports enable row level security;
drop policy if exists "Signed in users can submit app errors" on public.app_error_reports;
create policy "Signed in users can submit app errors" on public.app_error_reports
 for insert to authenticated with check(user_id=auth.uid());
revoke all on public.app_error_reports from anon,public;
grant insert on public.app_error_reports to authenticated;

create or replace function public.admin_get_support_inbox()
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_result jsonb;
begin
 if auth.uid() is null or not public.is_hearttalk_admin() then raise exception 'Admin access required'; end if;
 select coalesce(jsonb_agg(x),'[]'::jsonb) into v_result from (
  select jsonb_build_object(
   'thread_id',t.id,'user_id',t.user_id,'subject',t.subject,'status',t.status,
   'created_at',t.created_at,'updated_at',t.updated_at,
   'email',u.email,'display_name',p.display_name,'username',p.username,
   'messages',coalesce((select jsonb_agg(jsonb_build_object('id',m.id,'sender_role',m.sender_role,'message',m.message,'created_at',m.created_at) order by m.created_at)
      from public.support_messages m where m.thread_id=t.id),'[]'::jsonb)
  ) x
  from public.support_threads t
  left join auth.users u on u.id=t.user_id
  left join public.profiles p on p.id=t.user_id
  order by t.updated_at desc limit 100
 ) q;
 return v_result;
end; $$;
revoke all on function public.admin_get_support_inbox() from public,anon;
grant execute on function public.admin_get_support_inbox() to authenticated;

create or replace function public.admin_reply_support_thread(p_thread_id uuid,p_message text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_admin uuid:=auth.uid(); v_status text;
begin
 if v_admin is null or not public.is_hearttalk_admin() then raise exception 'Admin access required'; end if;
 if p_message is null or char_length(trim(p_message))<1 or char_length(p_message)>4000 then raise exception 'Reply must be 1 to 4000 characters'; end if;
 select status into v_status from public.support_threads where id=p_thread_id for update;
 if not found then raise exception 'Support conversation not found'; end if;
 if v_status='closed' then raise exception 'This support conversation is closed'; end if;
 insert into public.support_messages(thread_id,sender_id,sender_role,message)
 values(p_thread_id,v_admin,'admin',trim(p_message));
 update public.support_threads set status='answered',updated_at=now() where id=p_thread_id;
 return jsonb_build_object('success',true);
end; $$;
revoke all on function public.admin_reply_support_thread(uuid,text) from public,anon;
grant execute on function public.admin_reply_support_thread(uuid,text) to authenticated;

create or replace function public.admin_set_support_status(p_thread_id uuid,p_status text)
returns boolean language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or not public.is_hearttalk_admin() then raise exception 'Admin access required'; end if;
 if p_status not in ('open','answered','closed') then raise exception 'Invalid support status'; end if;
 update public.support_threads set status=p_status,updated_at=now() where id=p_thread_id;
 if not found then raise exception 'Support conversation not found'; end if;
 return true;
end; $$;
revoke all on function public.admin_set_support_status(uuid,text) from public,anon;
grant execute on function public.admin_set_support_status(uuid,text) to authenticated;

create or replace function public.admin_get_app_errors()
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_result jsonb;
begin
 if auth.uid() is null or not public.is_hearttalk_admin() then raise exception 'Admin access required'; end if;
 select coalesce(jsonb_agg(x),'[]'::jsonb) into v_result from (
  select jsonb_build_object('id',e.id,'user_id',e.user_id,'source',e.source,
   'error_type',e.error_type,'message',e.message,'stack',e.stack,'page',e.page,
   'app_version',e.app_version,'status',e.status,'created_at',e.created_at,
   'email',u.email,'display_name',p.display_name)
  x from public.app_error_reports e
  left join auth.users u on u.id=e.user_id
  left join public.profiles p on p.id=e.user_id
  order by e.created_at desc limit 200
 ) q;
 return v_result;
end; $$;
revoke all on function public.admin_get_app_errors() from public,anon;
grant execute on function public.admin_get_app_errors() to authenticated;

create or replace function public.admin_set_app_error_status(p_error_id bigint,p_status text)
returns boolean language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null or not public.is_hearttalk_admin() then raise exception 'Admin access required'; end if;
 if p_status not in ('open','investigating','resolved','ignored') then raise exception 'Invalid error status'; end if;
 update public.app_error_reports set status=p_status,
  resolved_at=case when p_status='resolved' then now() else null end,
  resolved_by=case when p_status='resolved' then auth.uid() else null end
 where id=p_error_id;
 if not found then raise exception 'Error report not found'; end if;
 return true;
end; $$;
revoke all on function public.admin_set_app_error_status(bigint,text) from public,anon;
grant execute on function public.admin_set_app_error_status(bigint,text) to authenticated;

-- Make support messages available to authenticated thread participants in Realtime.
do $$ begin
 if not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='support_messages') then
  alter publication supabase_realtime add table public.support_messages;
 end if;
end $$;
