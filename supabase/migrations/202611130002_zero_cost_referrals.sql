-- HeartTalk zero-cost referral rewards (no SMS or payment provider required)
alter table public.profiles add column if not exists referral_code text;
alter table public.profiles add column if not exists referred_by uuid references auth.users(id);
create unique index if not exists profiles_referral_code_unique on public.profiles(referral_code) where referral_code is not null;

alter table public.wallet_ledger drop constraint if exists wallet_ledger_entry_type_check;
alter table public.wallet_ledger add constraint wallet_ledger_entry_type_check
 check (entry_type in ('purchase','spend','refund','admin_adjustment','referral_reward'));

create table if not exists public.hearttalk_referrals (
 id bigint generated by default as identity primary key,
 referrer_id uuid not null references auth.users(id) on delete cascade,
 referred_user_id uuid not null unique references auth.users(id) on delete cascade,
 referral_code text not null,
 reward_coins integer not null default 100 check(reward_coins=100),
 created_at timestamptz not null default now(),
 check(referrer_id <> referred_user_id)
);
alter table public.hearttalk_referrals enable row level security;
revoke all on public.hearttalk_referrals from anon,authenticated,public;
grant select on public.hearttalk_referrals to authenticated;
drop policy if exists "Referral participants can view own referrals" on public.hearttalk_referrals;
create policy "Referral participants can view own referrals" on public.hearttalk_referrals
 for select to authenticated using(referrer_id=auth.uid() or referred_user_id=auth.uid());

create or replace function public.hearttalk_get_my_referral_code()
returns text language plpgsql security definer set search_path=public,pg_temp as $$
declare v_code text;
begin
 if auth.uid() is null then raise exception 'Login required'; end if;
 update public.profiles set referral_code=coalesce(referral_code,'HT'||upper(substr(replace(auth.uid()::text,'-',''),1,10)))
 where id=auth.uid();
 select referral_code into v_code from public.profiles where id=auth.uid();
 return v_code;
end; $$;

create or replace function public.hearttalk_claim_referral(p_referral_code text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_referrer uuid; v_user uuid:=auth.uid(); v_code text:=upper(trim(coalesce(p_referral_code,'')));
begin
 if v_user is null then raise exception 'Login required'; end if;
 if v_code='' then return jsonb_build_object('ok',false,'reason','missing_code'); end if;
 select id into v_referrer from public.profiles where upper(referral_code)=v_code;
 if v_referrer is null then return jsonb_build_object('ok',false,'reason','invalid_code'); end if;
 if v_referrer=v_user then return jsonb_build_object('ok',false,'reason','self_referral'); end if;
 if exists(select 1 from public.hearttalk_referrals where referred_user_id=v_user) then
  return jsonb_build_object('ok',false,'reason','already_claimed');
 end if;
 update public.profiles set referred_by=v_referrer where id=v_user and referred_by is null;
 if not found then return jsonb_build_object('ok',false,'reason','already_referred'); end if;
 insert into public.hearttalk_referrals(referrer_id,referred_user_id,referral_code)
 values(v_referrer,v_user,v_code);
 insert into public.wallet_ledger(user_id,amount,entry_type,reference_id)
 values(v_referrer,100,'referral_reward','referral:'||v_user::text);
 return jsonb_build_object('ok',true,'reward_coins',100);
end; $$;

revoke all on function public.hearttalk_get_my_referral_code() from public,anon;
revoke all on function public.hearttalk_claim_referral(text) from public,anon;
grant execute on function public.hearttalk_get_my_referral_code() to authenticated;
grant execute on function public.hearttalk_claim_referral(text) to authenticated;
