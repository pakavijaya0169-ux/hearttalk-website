-- HeartTalk business rules update (2026-11-26)
-- Free chat; eligible male User <-> approved female Host calls are billed to the User
-- regardless of call initiator. Voice 2 coins/minute, video 5 coins/minute.
-- Partial minutes round up. Host/platform split 50/50. No historical rows are rewritten.

create or replace function public.hearttalk_end_chat_billing(p_session_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_s public.hearttalk_chat_sessions%rowtype; v_seconds integer; v_end timestamptz;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 select * into v_s from public.hearttalk_chat_sessions where id=p_session_id and user_id=v_user for update;
 if not found then raise exception 'Chat session not found'; end if;
 if v_s.status<>'active' then return jsonb_build_object('session_id',v_s.id,'charged_coins',0,'host_earned_coins',0,'status','free'); end if;
 v_end:=least(now(),coalesce(v_s.last_heartbeat_at,v_s.started_at)+interval '20 seconds');
 v_seconds:=greatest(0,extract(epoch from(v_end-v_s.started_at))::integer);
 update public.hearttalk_chat_sessions set ended_at=v_end,elapsed_seconds=v_seconds,charged_coins=0,host_earned_coins=0,status='no_charge' where id=p_session_id;
 return jsonb_build_object('session_id',p_session_id,'elapsed_seconds',v_seconds,'charged_coins',0,'host_earned_coins',0,'status','free');
end; $$;
revoke all on function public.hearttalk_end_chat_billing(uuid) from public,anon;
grant execute on function public.hearttalk_end_chat_billing(uuid) to authenticated;

-- Keep old chat earnings/history intact; stop future free-chat sessions becoming cash earnings.
drop trigger if exists hearttalk_host_cash_credit_chat on public.hearttalk_chat_session_earnings;

alter table public.call_sessions
 add column if not exists billed_user_id uuid references auth.users(id) on delete restrict,
 add column if not exists billed_host_id uuid references auth.users(id) on delete restrict,
 add column if not exists billed_seconds integer not null default 0,
 add column if not exists charged_coins integer not null default 0,
 add column if not exists host_earned_coins integer not null default 0,
 add column if not exists platform_earned_coins integer not null default 0,
 add column if not exists billing_status text not null default 'not_billable';

create table if not exists public.hearttalk_call_session_earnings (
 id bigint generated by default as identity primary key,
 call_id uuid not null unique references public.call_sessions(id) on delete restrict,
 host_id uuid not null references auth.users(id) on delete restrict,
 user_id uuid not null references auth.users(id) on delete restrict,
 call_type text not null check(call_type in ('voice','video')),
 billed_seconds integer not null check(billed_seconds>=0),
 charged_coins integer not null check(charged_coins>=0),
 earned_coins integer not null check(earned_coins>=0),
 created_at timestamptz not null default now()
);
alter table public.hearttalk_call_session_earnings enable row level security;
revoke all on public.hearttalk_call_session_earnings from public,anon,authenticated;
grant select on public.hearttalk_call_session_earnings to authenticated;
drop policy if exists "Call participants can view own call earnings" on public.hearttalk_call_session_earnings;
create policy "Call participants can view own call earnings" on public.hearttalk_call_session_earnings
 for select to authenticated using(host_id=auth.uid() or user_id=auth.uid());

create or replace function public.hearttalk_credit_host_cash_from_call_earning()
returns trigger language plpgsql security definer set search_path='' as $$
begin
 if new.earned_coins>0 then
  insert into public.hearttalk_host_cash_ledger(host_id,amount_paise,entry_type,reference_id,source_reference,note,created_by)
  values(new.host_id,new.earned_coins::bigint*50,'earning_credit',new.call_id,'call:'||new.call_id::text,'Call earnings converted at ₹0.50 per Host coin',null)
  on conflict(host_id,source_reference) do nothing;
 end if;
 return new;
end; $$;
revoke all on function public.hearttalk_credit_host_cash_from_call_earning() from public,anon,authenticated;
drop trigger if exists hearttalk_host_cash_credit_call on public.hearttalk_call_session_earnings;
create trigger hearttalk_host_cash_credit_call after insert on public.hearttalk_call_session_earnings
 for each row execute function public.hearttalk_credit_host_cash_from_call_earning();

create or replace function public.hearttalk_end_call(target_call_id uuid, final_status text default 'ended')
returns jsonb language plpgsql security definer set search_path='' as $$
declare
 v_actor uuid:=auth.uid(); v_call public.call_sessions%rowtype; v_host uuid; v_user uuid;
 v_seconds integer; v_rate integer; v_coins integer; v_host_share integer; v_platform_share integer; v_balance bigint;
begin
 if v_actor is null then raise exception 'Authentication required'; end if;
 if final_status not in ('rejected','ended','cancelled','busy') then raise exception 'Invalid final call status'; end if;
 select * into v_call from public.call_sessions where id=target_call_id and (caller_id=v_actor or callee_id=v_actor) for update;
 if not found then raise exception 'Call not found'; end if;
 if v_call.status not in ('ringing','accepted') then
  return jsonb_build_object('updated',false,'status',v_call.status,'charged_coins',v_call.charged_coins,'host_earned_coins',v_call.host_earned_coins,'billing_status',v_call.billing_status);
 end if;
 update public.call_sessions set status=final_status,ended_at=now() where id=target_call_id and status in ('ringing','accepted');
 if final_status<>'ended' or v_call.status<>'accepted' or v_call.started_at is null then
  return jsonb_build_object('updated',true,'status',final_status,'charged_coins',0,'billing_status','not_billable');
 end if;
 select h.user_id into v_host from public.hosts h
 join public.host_applications a on a.user_id=h.user_id and a.status='approved'
 join public.host_kyc_documents d on d.user_id=h.user_id and d.document_type='video_selfie' and d.status='approved'
 where h.host_status='active' and h.user_id in (v_call.caller_id,v_call.callee_id) limit 1;
 if v_host is null then
  update public.call_sessions set billing_status='not_billable' where id=target_call_id;
  return jsonb_build_object('updated',true,'status','ended','charged_coins',0,'billing_status','not_billable');
 end if;
 v_user:=case when v_call.caller_id=v_host then v_call.callee_id else v_call.caller_id end;
 if not exists(select 1 from public.profiles p where p.id=v_user and lower(coalesce(p.gender,''))='male') then
  update public.call_sessions set billing_status='not_billable' where id=target_call_id;
  return jsonb_build_object('updated',true,'status','ended','charged_coins',0,'billing_status','not_billable');
 end if;
 v_seconds:=greatest(0,extract(epoch from(now()-v_call.started_at))::integer);
 v_rate:=case when v_call.call_type='voice' then 2 else 5 end;
 v_coins:=case when v_seconds=0 then 0 else ceil(v_seconds/60.0)::integer*v_rate end;
 v_host_share:=floor(v_coins*0.50)::integer; v_platform_share:=v_coins-v_host_share;
 perform 1 from auth.users where id=v_user for update;
 select coalesce(sum(amount),0) into v_balance from public.wallet_ledger where user_id=v_user;
 if v_balance<v_coins then
  update public.call_sessions set billed_user_id=v_user,billed_host_id=v_host,billed_seconds=v_seconds,charged_coins=0,host_earned_coins=0,platform_earned_coins=0,billing_status='insufficient_coins' where id=target_call_id;
  return jsonb_build_object('updated',true,'status','ended','required_coins',v_coins,'charged_coins',0,'billing_status','insufficient_coins');
 end if;
 if v_coins>0 then insert into public.wallet_ledger(user_id,amount,entry_type,reference_id) values(v_user,-v_coins,'spend','call_session:'||target_call_id::text); end if;
 update public.call_sessions set billed_user_id=v_user,billed_host_id=v_host,billed_seconds=v_seconds,charged_coins=v_coins,host_earned_coins=v_host_share,platform_earned_coins=v_platform_share,billing_status=case when v_coins=0 then 'no_charge' else 'charged' end where id=target_call_id;
 insert into public.hearttalk_call_session_earnings(call_id,host_id,user_id,call_type,billed_seconds,charged_coins,earned_coins)
 values(target_call_id,v_host,v_user,v_call.call_type,v_seconds,v_coins,v_host_share) on conflict(call_id) do nothing;
 return jsonb_build_object('updated',true,'status','ended','billed_seconds',v_seconds,'charged_coins',v_coins,'host_earned_coins',v_host_share,'platform_earned_coins',v_platform_share,'billing_status',case when v_coins=0 then 'no_charge' else 'charged' end);
end; $$;
revoke all on function public.hearttalk_end_call(uuid,text) from public,anon;
grant execute on function public.hearttalk_end_call(uuid,text) to authenticated;

-- Apply 50/50 to new gifts only; prior events and ledgers are immutable.
create or replace function public.hearttalk_send_gift(target_host_id uuid, selected_gift_code text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_sender uuid:=auth.uid(); v_price integer; v_host_share integer; v_platform_share integer; v_event uuid; v_balance bigint;
begin
 if v_sender is null then raise exception 'Authentication required'; end if;
 if target_host_id is null or target_host_id=v_sender then raise exception 'Choose another member'; end if;
 if not exists(select 1 from public.hosts h join public.host_applications a on a.user_id=h.user_id and a.status='approved'
  where h.user_id=target_host_id and h.host_status='active') then raise exception 'Host is not approved'; end if;
 select coin_price into v_price from public.hearttalk_gift_catalog where gift_code=selected_gift_code and active=true;
 if v_price is null then raise exception 'Gift is unavailable'; end if;
 perform 1 from auth.users where id=v_sender for update;
 select coalesce(sum(amount),0) into v_balance from public.wallet_ledger where user_id=v_sender;
 if v_balance<v_price then raise exception 'Not enough coins'; end if;
 v_host_share:=floor(v_price*0.50)::integer; v_platform_share:=v_price-v_host_share;
 insert into public.wallet_ledger(user_id,amount,entry_type,reference_id) values(v_sender,-v_price,'spend','gift:'||gen_random_uuid()::text);
 insert into public.hearttalk_gift_events(sender_id,host_id,gift_code,coin_price,host_share_coins,platform_share_coins) values(v_sender,target_host_id,selected_gift_code,v_price,v_host_share,v_platform_share) returning id into v_event;
 insert into public.hearttalk_host_earnings(host_id,gift_event_id,earned_coins) values(target_host_id,v_event,v_host_share);
 return jsonb_build_object('gift_event_id',v_event,'coin_price',v_price,'host_earned_coins',v_host_share,'platform_earned_coins',v_platform_share,'status','recorded');
end; $$;
revoke all on function public.hearttalk_send_gift(uuid,text) from public,anon;
grant execute on function public.hearttalk_send_gift(uuid,text) to authenticated;

-- Include call earnings in Host earnings; keep existing gift/chat history untouched.
create or replace function public.hearttalk_get_host_earnings()
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_total bigint; v_count bigint; v_recent jsonb;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 select coalesce((select sum(earned_coins) from public.hearttalk_host_earnings where host_id=v_user),0)
  +coalesce((select sum(earned_coins) from public.hearttalk_chat_session_earnings where host_id=v_user),0)
  +coalesce((select sum(earned_coins) from public.hearttalk_call_session_earnings where host_id=v_user),0),
  (select count(*) from public.hearttalk_host_earnings where host_id=v_user)
  +(select count(*) from public.hearttalk_chat_session_earnings where host_id=v_user)
  +(select count(*) from public.hearttalk_call_session_earnings where host_id=v_user)
 into v_total,v_count;
 select coalesce(jsonb_agg(item),'[]'::jsonb) into v_recent from (
  select item,sort_at from (
   select jsonb_build_object('gift_event_id',e.gift_event_id,'earned_coins',e.earned_coins,'created_at',e.created_at,'gift_title',c.title,'emoji',c.emoji) item,e.created_at sort_at
   from public.hearttalk_host_earnings e join public.hearttalk_gift_events g on g.id=e.gift_event_id join public.hearttalk_gift_catalog c on c.gift_code=g.gift_code where e.host_id=v_user
   union all
   select jsonb_build_object('gift_event_id',null,'earned_coins',e.earned_coins,'created_at',e.created_at,'gift_title','Chat earnings','emoji','💬') item,e.created_at sort_at
   from public.hearttalk_chat_session_earnings e where e.host_id=v_user
   union all
   select jsonb_build_object('gift_event_id',null,'earned_coins',e.earned_coins,'created_at',e.created_at,'gift_title',case when e.call_type='voice' then 'Voice call' else 'Video call' end,'emoji','📞') item,e.created_at sort_at
   from public.hearttalk_call_session_earnings e where e.host_id=v_user
  ) x order by sort_at desc limit 50
 ) q;
 return jsonb_build_object('earned_coins',v_total,'gift_count',v_count,'history',v_recent,'cash_withdrawal_enabled',false);
end; $$;
revoke all on function public.hearttalk_get_host_earnings() from public;
grant execute on function public.hearttalk_get_host_earnings() to authenticated;
