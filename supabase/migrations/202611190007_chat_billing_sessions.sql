-- HeartTalk chat billing sessions (additive only; existing chat/wallet data is preserved).
-- Rate: 4 coins per 5 minutes, prorated by elapsed seconds, rounded down.
-- Host share: 50% of whole coins charged; remainder stays platform-side.

create table if not exists public.hearttalk_chat_sessions (
 id uuid primary key default gen_random_uuid(),
 user_id uuid not null references auth.users(id) on delete restrict,
 host_id uuid not null references auth.users(id) on delete restrict,
 started_at timestamptz not null default now(),
 ended_at timestamptz,
 elapsed_seconds integer,
 charged_coins integer not null default 0 check(charged_coins>=0),
 host_earned_coins integer not null default 0 check(host_earned_coins>=0),
 status text not null default 'active' check(status in ('active','ended','no_charge')),
 created_at timestamptz not null default now(),
 check(user_id<>host_id)
);
create index if not exists hearttalk_chat_sessions_user_started_idx
 on public.hearttalk_chat_sessions(user_id,started_at desc);
create index if not exists hearttalk_chat_sessions_host_started_idx
 on public.hearttalk_chat_sessions(host_id,started_at desc);
alter table public.hearttalk_chat_sessions enable row level security;
revoke all on public.hearttalk_chat_sessions from public,anon,authenticated;
grant select on public.hearttalk_chat_sessions to authenticated;
drop policy if exists "Chat participants view their billing sessions" on public.hearttalk_chat_sessions;
create policy "Chat participants view their billing sessions" on public.hearttalk_chat_sessions
 for select to authenticated using(user_id=auth.uid() or host_id=auth.uid());

create table if not exists public.hearttalk_chat_session_earnings (
 id bigint generated by default as identity primary key,
 session_id uuid not null unique references public.hearttalk_chat_sessions(id) on delete restrict,
 host_id uuid not null references auth.users(id) on delete restrict,
 earned_coins integer not null check(earned_coins>=0),
 created_at timestamptz not null default now()
);
alter table public.hearttalk_chat_session_earnings enable row level security;
revoke all on public.hearttalk_chat_session_earnings from public,anon,authenticated;
grant select on public.hearttalk_chat_session_earnings to authenticated;
drop policy if exists "Hosts view chat session earnings" on public.hearttalk_chat_session_earnings;
create policy "Hosts view chat session earnings" on public.hearttalk_chat_session_earnings
 for select to authenticated using(host_id=auth.uid());

create or replace function public.hearttalk_start_chat_billing(p_host_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_session uuid;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if p_host_id is null or p_host_id=v_user then raise exception 'Invalid chat partner'; end if;
 -- Prevent overlapping billable chat sessions for the same user-host pair.
 perform 1 from auth.users where id=v_user for update;
 select id into v_session from public.hearttalk_chat_sessions
 where user_id=v_user and host_id=p_host_id and status='active'
 order by started_at desc limit 1;
 if v_session is null then
  insert into public.hearttalk_chat_sessions(user_id,host_id) values(v_user,p_host_id) returning id into v_session;
 end if;
 return jsonb_build_object('session_id',v_session,'started',true);
end; $$;
revoke all on function public.hearttalk_start_chat_billing(uuid) from public;
grant execute on function public.hearttalk_start_chat_billing(uuid) to authenticated;

create or replace function public.hearttalk_end_chat_billing(p_session_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare
 v_user uuid:=auth.uid(); v_s public.hearttalk_chat_sessions%rowtype;
 v_seconds integer; v_coins integer; v_host_share integer; v_balance bigint;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 select * into v_s from public.hearttalk_chat_sessions
 where id=p_session_id and user_id=v_user for update;
 if not found then raise exception 'Chat billing session not found'; end if;
 if v_s.status<>'active' then
  return jsonb_build_object('session_id',v_s.id,'elapsed_seconds',v_s.elapsed_seconds,
   'charged_coins',v_s.charged_coins,'host_earned_coins',v_s.host_earned_coins,'status',v_s.status);
 end if;
 v_seconds:=greatest(0,extract(epoch from (now()-v_s.started_at))::integer);
 v_coins:=floor(v_seconds*4/300.0)::integer;
 v_host_share:=floor(v_coins*0.50)::integer;
 perform 1 from auth.users where id=v_user for update;
 select coalesce(sum(amount),0) into v_balance from public.wallet_ledger where user_id=v_user;
 if v_balance<v_coins then
  update public.hearttalk_chat_sessions set ended_at=now(),elapsed_seconds=v_seconds,
   charged_coins=0,host_earned_coins=0,status='no_charge' where id=p_session_id;
  return jsonb_build_object('session_id',p_session_id,'elapsed_seconds',v_seconds,
   'required_coins',v_coins,'charged_coins',0,'host_earned_coins',0,'status','insufficient_coins');
 end if;
 if v_coins>0 then
  insert into public.wallet_ledger(user_id,amount,entry_type,reference_id)
  values(v_user,-v_coins,'spend','chat_session:'||p_session_id::text);
 end if;
 update public.hearttalk_chat_sessions set ended_at=now(),elapsed_seconds=v_seconds,
  charged_coins=v_coins,host_earned_coins=v_host_share,
  status=case when v_coins=0 then 'no_charge' else 'ended' end
 where id=p_session_id;
 insert into public.hearttalk_chat_session_earnings(session_id,host_id,earned_coins)
 values(p_session_id,v_s.host_id,v_host_share) on conflict(session_id) do nothing;
 return jsonb_build_object('session_id',p_session_id,'elapsed_seconds',v_seconds,
  'charged_coins',v_coins,'host_earned_coins',v_host_share,'status',case when v_coins=0 then 'no_charge' else 'charged' end);
end; $$;
revoke all on function public.hearttalk_end_chat_billing(uuid) from public;
grant execute on function public.hearttalk_end_chat_billing(uuid) to authenticated;
