create or replace function public.hearttalk_purchase_cosmetic(p_item_code text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_item public.hearttalk_cosmetic_catalog%rowtype; v_balance bigint;
begin
 if v_user is null then raise exception 'Please log in first'; end if;
 select * into v_item from public.hearttalk_cosmetic_catalog where item_code=p_item_code and active=true;
 if not found then raise exception 'This store item is unavailable'; end if;
 perform 1 from auth.users where id=v_user for update;
 if exists(select 1 from public.hearttalk_user_cosmetics where user_id=v_user and item_code=p_item_code) then
  return jsonb_build_object('status','already_owned','item_code',p_item_code,'coin_price',v_item.coin_price);
 end if;
 select coalesce(sum(amount),0) into v_balance from public.wallet_ledger where user_id=v_user;
 if v_balance<v_item.coin_price then raise exception 'Not enough coins. Please recharge your wallet.'; end if;
 insert into public.wallet_ledger(user_id,amount,entry_type,reference_id)
 values(v_user,-v_item.coin_price,'spend','cosmetic:'||p_item_code);
 insert into public.hearttalk_user_cosmetics(user_id,item_code,purchased_price)
 values(v_user,p_item_code,v_item.coin_price);
 return jsonb_build_object('status','purchased','item_code',p_item_code,'coin_price',v_item.coin_price,'balance_after',v_balance-v_item.coin_price);
end; $$;
revoke all on function public.hearttalk_purchase_cosmetic(text) from public;
grant execute on function public.hearttalk_purchase_cosmetic(text) to authenticated;

create or replace function public.hearttalk_equip_cosmetic(p_item_code text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_item public.hearttalk_cosmetic_catalog%rowtype;
begin
 if v_user is null then raise exception 'Please log in first'; end if;
 select c.* into v_item from public.hearttalk_cosmetic_catalog c
 join public.hearttalk_user_cosmetics u on u.item_code=c.item_code and u.user_id=v_user
 where c.item_code=p_item_code and c.active=true;
 if not found then raise exception 'Purchase this item before applying it'; end if;
 if v_item.item_type='frame' then
  update public.profiles set equipped_frame_code=p_item_code where id=v_user;
 else
  update public.profiles set equipped_wallpaper_code=p_item_code where id=v_user;
 end if;
 return jsonb_build_object('status','equipped','item_code',p_item_code,'item_type',v_item.item_type);
end; $$;
revoke all on function public.hearttalk_equip_cosmetic(text) from public;
grant execute on function public.hearttalk_equip_cosmetic(text) to authenticated;

create or replace function public.hearttalk_remove_cosmetic(p_item_type text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid();
begin
 if v_user is null then raise exception 'Please log in first'; end if;
 if p_item_type='frame' then update public.profiles set equipped_frame_code=null where id=v_user;
 elsif p_item_type='wallpaper' then update public.profiles set equipped_wallpaper_code=null where id=v_user;
 else raise exception 'Invalid cosmetic type'; end if;
 return jsonb_build_object('status','removed','item_type',p_item_type);
end; $$;
revoke all on function public.hearttalk_remove_cosmetic(text) from public;
grant execute on function public.hearttalk_remove_cosmetic(text) to authenticated;
