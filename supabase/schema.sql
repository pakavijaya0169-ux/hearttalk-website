-- HeartTalk database setup: profiles + private direct messages
-- Run in Supabase Dashboard > SQL Editor. Safe to run again.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  username text unique,
  age integer check (age is null or age between 18 and 100),
  country text not null default '',
  bio text not null default '',
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles add column if not exists display_name text not null default '';
alter table public.profiles add column if not exists username text;
alter table public.profiles add column if not exists age integer;
alter table public.profiles add column if not exists country text not null default '';
alter table public.profiles add column if not exists bio text not null default '';
alter table public.profiles add column if not exists avatar_url text;
alter table public.profiles add column if not exists created_at timestamptz not null default now();
alter table public.profiles add column if not exists updated_at timestamptz not null default now();

create unique index if not exists profiles_username_unique_idx
on public.profiles(username) where username is not null and username <> '';

alter table public.profiles enable row level security;

drop policy if exists "Profiles are viewable by authenticated users" on public.profiles;
drop policy if exists "Users can create their own profile" on public.profiles;
drop policy if exists "Users can update their own profile" on public.profiles;
drop policy if exists "Users can view profiles" on public.profiles;
drop policy if exists "Users can create own profile" on public.profiles;
drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can view profiles"
on public.profiles for select to authenticated using (true);
create policy "Users can create own profile"
on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Users can update own profile"
on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create or replace function public.set_profile_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_updated_at on public.profiles;
create trigger profiles_updated_at before update on public.profiles
for each row execute function public.set_profile_updated_at();

create or replace function public.handle_new_hearttalk_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_hearttalk_auth_user_created on auth.users;
create trigger on_hearttalk_auth_user_created after insert on auth.users
for each row execute function public.handle_new_hearttalk_user();

-- Private one-to-one messages. Only sender and receiver can read a message.
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  receiver_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 2000),
  created_at timestamptz not null default now(),
  constraint messages_no_self_message check (sender_id <> receiver_id)
);

create index if not exists messages_sender_created_idx
on public.messages(sender_id, created_at desc);
create index if not exists messages_receiver_created_idx
on public.messages(receiver_id, created_at desc);

alter table public.messages enable row level security;
drop policy if exists "Users can read their own messages" on public.messages;
drop policy if exists "Users can send messages as themselves" on public.messages;
drop policy if exists "Users can delete their own sent messages" on public.messages;

create policy "Users can read their own messages"
on public.messages for select to authenticated
using (auth.uid() = sender_id or auth.uid() = receiver_id);

create policy "Users can send messages as themselves"
on public.messages for insert to authenticated
with check (auth.uid() = sender_id and sender_id <> receiver_id);

create policy "Users can delete their own sent messages"
on public.messages for delete to authenticated
using (auth.uid() = sender_id);

-- Enable realtime updates for the chat table, without failing if already enabled.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;
