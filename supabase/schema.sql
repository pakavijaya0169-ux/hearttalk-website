for insert to authenticated with check (auth.uid() = caller_id and caller_id <> callee_id);
drop policy if exists "Call participants can update call" on public.call_sessions;
create policy "Call participants can update call" on public.call_sessions
for update to authenticated using (auth.uid() = caller_id or auth.uid() = callee_id)
with check (auth.uid() = caller_id or auth.uid() = callee_id);

-- WebRTC offer/answer/ICE signaling. Only the two call participants can read/write.
create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  call_id uuid not null references public.call_sessions(id) on delete cascade,
  sender_id uuid not null references auth.users(id) on delete cascade,
  signal_type text not null check (signal_type in ('offer','answer','ice','hangup','reject')),
  payload jsonb,
  created_at timestamptz not null default now()
);
create index if not exists call_signals_call_created_idx on public.call_signals(call_id, created_at);
alter table public.call_signals enable row level security;
drop policy if exists "Call participants can read signaling" on public.call_signals;
create policy "Call participants can read signaling" on public.call_signals
for select to authenticated using (
  exists(select 1 from public.call_sessions c where c.id = call_id and (c.caller_id = auth.uid() or c.callee_id = auth.uid()))
);
drop policy if exists "Call participants can send signaling" on public.call_signals;
create policy "Call participants can send signaling" on public.call_signals
for insert to authenticated with check (
  sender_id = auth.uid() and exists(
    select 1 from public.call_sessions c where c.id = call_id and (c.caller_id = auth.uid() or c.callee_id = auth.uid())
  )
);

