-- HeartTalk safety tools: user reports and blocks
-- Run once in Supabase Dashboard > SQL Editor. Safe to run again.

create table if not exists public.blocked_users (
  blocker_id uuid not null references auth.users(id) on delete cascade,
  blocked_user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_user_id),
  check (blocker_id <> blocked_user_id)
);
alter table public.blocked_users enable row level security;
drop policy if exists "Users can view their own blocks" on public.blocked_users;
create policy "Users can view their own blocks" on public.blocked_users
for select to authenticated using (blocker_id = auth.uid() or blocked_user_id = auth.uid());
drop policy if exists "Users can block members" on public.blocked_users;
create policy "Users can block members" on public.blocked_users
for insert to authenticated with check (blocker_id = auth.uid() and blocked_user_id <> auth.uid());
drop policy if exists "Users can unblock members" on public.blocked_users;
create policy "Users can unblock members" on public.blocked_users
for delete to authenticated using (blocker_id = auth.uid());

create table if not exists public.user_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reported_user_id uuid not null references auth.users(id) on delete cascade,
  reason text not null check (char_length(reason) between 2 and 80),
  details text not null default '' check (char_length(details) <= 1000),
  status text not null default 'open' check (status in ('open','reviewing','resolved','dismissed')),
  created_at timestamptz not null default now(),
  check (reporter_id <> reported_user_id)
);
create index if not exists user_reports_status_created_idx on public.user_reports(status, created_at desc);
alter table public.user_reports enable row level security;
drop policy if exists "Users can submit reports" on public.user_reports;
create policy "Users can submit reports" on public.user_reports
for insert to authenticated with check (reporter_id = auth.uid() and reporter_id <> reported_user_id);
drop policy if exists "Users can view their own reports" on public.user_reports;
create policy "Users can view their own reports" on public.user_reports
for select to authenticated using (reporter_id = auth.uid());
