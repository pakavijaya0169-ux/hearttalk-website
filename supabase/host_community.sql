-- HeartTalk Host Community
-- Run in Supabase Dashboard > SQL Editor. Members are added by an admin using
-- their HeartTalk user ID; phone numbers are not needed or stored.
create or replace function public.hearttalk_is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.hearttalk_user_roles r
    where r.user_id = auth.uid() and r.role = 'admin'
  );
$$;
revoke all on function public.hearttalk_is_admin() from public;
grant execute on function public.hearttalk_is_admin() to authenticated;

create table if not exists public.hearttalk_host_community_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  added_by uuid not null references auth.users(id),
  joined_at timestamptz not null default now()
);
alter table public.hearttalk_host_community_members enable row level security;
drop policy if exists "Host community members can view membership" on public.hearttalk_host_community_members;
create policy "Host community members can view membership"
on public.hearttalk_host_community_members for select to authenticated
using (user_id = auth.uid() or public.hearttalk_is_admin());
drop policy if exists "Admins manage host community membership" on public.hearttalk_host_community_members;
create policy "Admins manage host community membership"
on public.hearttalk_host_community_members for all to authenticated
using (public.hearttalk_is_admin()) with check (public.hearttalk_is_admin());

create table if not exists public.hearttalk_host_community_messages (
  id bigint generated by default as identity primary key,
  author_id uuid not null references auth.users(id) on delete cascade,
  message_type text not null check (message_type in ('announcement','discussion')),
  message text not null check (char_length(message) between 1 and 3000),
  created_at timestamptz not null default now()
);
create index if not exists hearttalk_host_community_messages_created_idx
on public.hearttalk_host_community_messages(created_at desc);
alter table public.hearttalk_host_community_messages enable row level security;
drop policy if exists "Community members read host community messages" on public.hearttalk_host_community_messages;
create policy "Community members read host community messages"
on public.hearttalk_host_community_messages for select to authenticated
using (
  public.hearttalk_is_admin() or exists (
    select 1 from public.hearttalk_host_community_members m
    where m.user_id = auth.uid()
  )
);
drop policy if exists "Admins publish announcements and members discuss" on public.hearttalk_host_community_messages;
create policy "Admins publish announcements and members discuss"
on public.hearttalk_host_community_messages for insert to authenticated
with check (
  author_id = auth.uid()
  and (
    (message_type = 'announcement' and public.hearttalk_is_admin())
    or
    (message_type = 'discussion' and exists (
      select 1 from public.hearttalk_host_community_members m
      where m.user_id = auth.uid()
    ))
  )
);
drop policy if exists "Admins delete host community messages" on public.hearttalk_host_community_messages;
create policy "Admins delete host community messages"
on public.hearttalk_host_community_messages for delete to authenticated
using (public.hearttalk_is_admin());

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'hearttalk_host_community_messages'
  ) then
    alter publication supabase_realtime add table public.hearttalk_host_community_messages;
  end if;
end $$;
